export const dictionaries = { en, ja };
export type Lang = keyof typeof dictionaries;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  return s;
}

/** Translate a server-provided shelf key (Plex home) or pass through provider titles. */
export function shelfTitle(lang: Lang, title: string): string {
  return title in en ? translate(lang, title as Key) : title;
}

export function useT() {
  const lang = useSettings((s) => s.language);
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
